"""Generate kodetabell_ns3457-8.yaml: the NS 3457-8:2021 component code table, code and name, from
the visual transcription of the standard (resources/standards/ns3457/ns3457_pdf_extract.json, with
its 2026-09-25 corrections). Every level (1-3), names verbatim (`komponentfunksjon`).

    python gen_kodetabell_ns3457_8.py

Written 2026-10-05 because mengdetype_ns3457.yaml (built from ns3457_8_codes.py) is not that list:
200 extract codes are missing from it, 79 of its codes are not in the extract (JWB among them) and
272 names differ. mengdetype_ns3457.yaml stays for the mengdetype analysis only; every code check reads this table.
"""
import hashlib
import json
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")
HER = Path(__file__).resolve().parent
KILDE = Path("C:/workspace/resources/standards/ns3457/ns3457_pdf_extract.json")
UT = HER / "kodetabell_ns3457-8.yaml"
# Codes the transcription dropped, confirmed against the standard by a reader. Kept here so a
# regeneration keeps them.
#   SFZ 2026-11-04 (Edvard): HI90 RIV codes exhaust air valves (IfcAirTerminal) SFZ; a Z code
#   carries its parent's name (193 of 193 in the extract), SF is Fraluftsventiler.
TILLEGG = [{"code": "SFZ", "level": 3, "komponentfunksjon": "Fraluftsventiler"}]


def q(s: str) -> str:
    return "'" + str(s).replace("'", "''") + "'"


def main() -> int:
    raa = KILDE.read_bytes()
    x = json.loads(raa.decode("utf-8"))
    kjente = {c["code"] for c in x["codes"].values()}
    tillegg = [c for c in TILLEGG if c["code"] not in kjente]
    koder = sorted([*x["codes"].values(), *tillegg], key=lambda c: c["code"])
    nivaa = {n: sum(1 for c in koder if c["level"] == n) for n in (1, 2, 3)}
    linjer = [
        "# kodetabell_ns3457-8.yaml",
        "#",
        "# NS 3457-8:2021 component code table, code and name, levels 1-3. Ships with the tool; a",
        "# block's `kodetabell` / `kodeliste` names it (KNM funksjonskode, typenavn).",
        "#",
        "# Generated by 02_Arbeid/gen_kodetabell_ns3457_8.py from",
        f"#   {KILDE.as_posix()}",
        f"#   sha256 {hashlib.sha256(raa).hexdigest()}",
        f"#   {x['_meta'].get('source', '')}",
        f"# {len(koder)} codes: level 1 {nivaa[1]}, level 2 {nivaa[2]}, level 3 {nivaa[3]}. Names verbatim",
        "# (komponentfunksjon).",
        *(f"# Added by hand, dropped by the transcription: {c['code']} {c['komponentfunksjon']} (TILLEGG)."
          for c in tillegg),
    ]
    for c in koder:
        linjer.append(f"- {{kode: {q(c['code'])}, navn: {q(c['komponentfunksjon'])}}}")
    UT.write_text("\n".join(linjer) + "\n", encoding="utf-8")
    print(f"{UT.name}: {len(koder)} koder {nivaa}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
